// ===== DECISION EVENT =====
export type DecisionType = "triage" | "pairwise_compare";
export type TriageResult = "top" | "high" | "medium" | "low";
export type PairwiseResult = "item_a" | "item_b" | "tie" | "skip";

export interface DecisionEvent {
  id: string;
  sessionId: string;
  type: DecisionType;
  decision: TriageDecision | PairwiseDecision;
  createdAt: Date;
}

export interface TriageDecision {
  itemId: string;
  result: TriageResult;
}

export interface PairwiseDecision {
  itemAId: string;
  itemBId: string;
  result: PairwiseResult;
}

// ===== AUDIT LOG =====
export type AuditAction =
  | "item.purge"
  | "collection.purge"
  | "account.delete"
  | "item.delete"
  | "photo.delete";
export type AuditTargetType = "item" | "collection" | "user" | "photo";

export interface AuditLog {
  id: string;
  actorId: string;
  action: AuditAction;
  targetType: AuditTargetType;
  targetId: string;
  collectionId: string;
  metadata: Record<string, number> | null;
  createdAt: Date;
}

// Insert DTO — id + createdAt are generated by the repo. Literal unions make
// an illegal action/targetType unrepresentable at the only construction sites.
export interface NewAuditLog {
  actorId: string;
  action: AuditAction;
  targetType: AuditTargetType;
  targetId: string;
  collectionId: string;
  metadata?: Record<string, number>;
}

